import { useEffect, useRef } from 'react';
import type { ExplanationState } from '@/utils/explainClient';
import { Sparkles, Loader2, AlertCircle } from 'lucide-react';

interface ExplanationPanelProps {
  state: ExplanationState;
  onRetry: () => void;
}

/**
 * Secondary, clearly-labeled panel for the generated explanation.
 * It never replaces the confirmed verdict — it sits below it.
 */
export default function ExplanationPanel({ state, onRetry }: ExplanationPanelProps) {
  const hasContent = state.status !== 'idle';
  const prevStatus = useRef(state.status);

  useEffect(() => {
    prevStatus.current = state.status;
  }, [state.status]);

  if (!hasContent) return null;

  return (
    <div
      role="note"
      aria-label="Mock AI explanation"
      className={[
        'rounded-xl border border-dashed p-4 transition-all duration-200',
        state.status === 'error'
          ? 'border-amber-300 bg-amber-50'
          : 'border-sky-200 bg-sky-50/60',
      ].join(' ')}
    >
      <div className="mb-2 flex items-center justify-between gap-2">
        <span className="inline-flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wide text-sky-700">
          <Sparkles className="h-3.5 w-3.5" />
          Explanation — Mock AI
        </span>
        <span
          className="rounded-full border border-sky-200 bg-white px-2 py-0.5 text-[10px] font-medium uppercase tracking-wide text-sky-600"
          title="This text is generated by a mock adapter, not a real AI model. The verdict above is the authoritative result."
        >
          Not authoritative
        </span>
      </div>

      {state.status === 'loading' && (
        <p className="flex items-center gap-2 text-sm text-gray-600">
          <Loader2 className="h-4 w-4 animate-spin text-sky-600" />
          Generating explanation…
        </p>
      )}

      {state.status === 'error' && (
        <div className="flex items-start justify-between gap-3">
          <p className="flex items-start gap-2 text-sm text-amber-800">
            <AlertCircle className="mt-0.5 h-4 w-4 shrink-0 text-amber-600" />
            {state.message}
          </p>
          <button
            type="button"
            onClick={onRetry}
            className="shrink-0 rounded-lg border border-amber-300 bg-white px-3 py-1.5 text-xs font-medium text-amber-800 transition hover:bg-amber-100"
          >
            Try again
          </button>
        </div>
      )}

      {state.status === 'ok' && (
        <p className="text-sm leading-relaxed text-gray-700">{state.explanation}</p>
      )}
    </div>
  );
}
